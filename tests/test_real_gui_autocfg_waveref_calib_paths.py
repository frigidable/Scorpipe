"""Real GUI first-run contracts: SCORPIO air atlas and run-local calibration paths.

Regression for BTA N2146sat 2024-12-06: an AutoConfig created an invalid
project.wave_reference=UNKNOWN, while load_config redirected not-yet-created
03_bias / 04_flat outputs into the repository root instead of the run root.
These regressions are independent of observational data and run on any OS.
"""
from __future__ import annotations

from pathlib import Path

import pytest
import yaml

from scorpio_pipe.autocfg import AutoConfig
from scorpio_pipe.config import load_config
from scorpio_pipe.typed_config import build_typed_config


def _autocfg_for_run(run: Path, *, instrument: str = "SCORPIO") -> AutoConfig:
    return AutoConfig(
        data_dir=str(run.parent / "raw"),
        object_name="N2146sat",
        work_dir=".",
        calib={
            "superbias_path": "03_bias/superbias.fits",
            "superflat_path": "04_flat/superflat.fits",
        },
        frames={
            "obj": ["s228006/s22800607.fts"],
            "bias": [],
            "neon": [],
            "flat": [],
            "__setup__": {
                "instrument": instrument,
                "mode": "Spectra",
                "disperser": "VPHG1200B",
                "slit": "1.2",
                "binning": "1x2",
                "shape": "1032x2080",
            },
        },
    )


@pytest.mark.parametrize("instrument", ["SCORPIO", "SCORPIO1", "SCORPIO2"])
def test_gui_autoconfig_air_atlas_passes_strict_typed_schema(
    tmp_path: Path, instrument: str
) -> None:
    run = tmp_path / "run"
    run.mkdir()
    cfg_file = run / "config.yaml"
    cfg_file.write_text(
        _autocfg_for_run(run, instrument=instrument).to_yaml_text(),
        encoding="utf-8",
    )
    payload = yaml.safe_load(cfg_file.read_text(encoding="utf-8"))
    assert payload["project"]["wave_reference"] == "air"

    cfg = load_config(cfg_file)
    typed = build_typed_config(cfg, config_path=cfg_file)
    assert typed.project.wave_reference == "air"
    assert cfg["calib"]["superbias_path"] == str((run / "03_bias/superbias.fits").resolve())
    assert cfg["calib"]["superflat_path"] == str((run / "04_flat/superflat.fits").resolve())


def test_calibration_paths_never_follow_existing_repo_root_file(
    tmp_path: Path
) -> None:
    repo = tmp_path / "Scorpipe"
    repo.mkdir()
    (repo / "pyproject.toml").write_text("[project]\nname = 'scorpio-pipe'\n", encoding="utf-8")
    stray = repo / "03_bias" / "superbias.fits"
    stray.parent.mkdir()
    stray.write_bytes(b"unrelated output")
    run = repo / "workspace" / "06_12_2024" / "N2146sat_VPHG1200B_01"
    run.mkdir(parents=True)
    cfg_file = run / "config.yaml"
    cfg_file.write_text(_autocfg_for_run(run).to_yaml_text(), encoding="utf-8")

    cfg = load_config(cfg_file)
    assert Path(cfg["calib"]["superbias_path"]) == (run / "03_bias" / "superbias.fits")
    assert Path(cfg["calib"]["superbias_path"]) != stray
    assert Path(cfg["calib"]["superflat_path"]) == (run / "04_flat" / "superflat.fits")
    # Reload before or after output creation must not change the config target.
    (run / "03_bias").mkdir()
    (run / "03_bias/superbias.fits").write_bytes(b"output")
    cfg2 = load_config(cfg_file)
    assert cfg2["calib"]["superbias_path"] == cfg["calib"]["superbias_path"]


def test_explicit_absolute_and_legacy_project_relative_calibration_paths(
    tmp_path: Path
) -> None:
    repo = tmp_path / "Scorpipe"
    repo.mkdir()
    (repo / "pyproject.toml").write_text("[project]\nname = 'scorpio-pipe'\n", encoding="utf-8")
    run = repo / "work" / "target"
    run.mkdir(parents=True)
    absolute = tmp_path / "external" / "master_bias.fits"
    cfg = yaml.safe_load(_autocfg_for_run(run).to_yaml_text())
    cfg["calib"]["superbias_path"] = str(absolute)
    cfg["calib"]["superflat_path"] = "work/legacy/calib/superflat.fits"
    cfg_file = run / "config.yaml"
    cfg_file.write_text(yaml.safe_dump(cfg), encoding="utf-8")

    loaded = load_config(cfg_file)
    assert Path(loaded["calib"]["superbias_path"]) == absolute
    assert Path(loaded["calib"]["superflat_path"]) == repo / "work/legacy/calib/superflat.fits"


def test_manual_vacuum_choice_preserved_but_not_autogenerated(
    tmp_path: Path
) -> None:
    run = tmp_path / "run"
    run.mkdir()
    cfg = yaml.safe_load(_autocfg_for_run(run).to_yaml_text())
    cfg["project"]["wave_reference"] = "vacuum"
    cfg_file = run / "config.yaml"
    cfg_file.write_text(yaml.safe_dump(cfg), encoding="utf-8")
    loaded = load_config(cfg_file)
    assert build_typed_config(loaded, config_path=cfg_file).project.wave_reference == "vacuum"
